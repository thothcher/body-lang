/* ------------------------------------------------------------------
   ილუსტრაციული კითხვები — ავტომატურად ჟესტებიდან
------------------------------------------------------------------- */

function shortMeaning(g: Gesture): string {
  return g.meaning.split(" — ")[0].replace(/\.$/, "");
}

/** დეტერმინისტული არევა — SSR/CSR შეუსაბამობის თავიდან ასაცილებლად */
function seededShuffle<T>(arr: T[], seed: number): T[] {
  const out = [...arr];
  let s = seed;
  for (let i = out.length - 1; i > 0; i--) {
    s = (s * 1103515245 + 12345) % 2147483648;
    const j = s % (i + 1);
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

/** ყოველი ჟესტიდან აშენებს „რას ნიშნავს ეს პოზა?“ კითხვას. */
export function buildFigureQuestions(pool: Gesture[] = GESTURES): Question[] {
  return pool.map((g, idx) => {
    const distractorPool = GESTURES.filter(
      (o) => o.id !== g.id && o.tone !== g.tone,
    );
    const distractors = seededShuffle(distractorPool, idx + 7)
      .slice(0, 3)
      .map(shortMeaning);
    const correct = shortMeaning(g);
    const options = seededShuffle([correct, ...distractors], idx + 31);
    return {
      id: `fig-${g.id}`,
      chapter: g.chapter,
      part: g.part,
      kind: "figure" as const,
      gestureId: g.id,
      prompt: "რას ნიშნავს ეს პოზა?",
      options,
      answer: options.indexOf(correct),
      explain: g.detail,
      difficulty: 2 as const,
    };
  });
}

export const ALL_QUESTIONS: Question[] = [...TEXT_QUESTIONS, ...buildFigureQuestions()];

export function questionsForChapter(slug: string): Question[] {
  return ALL_QUESTIONS.filter((q) => q.chapter === slug);
}

export function questionsForPart(part: BodyPart): Question[] {
  return ALL_QUESTIONS.filter((q) => q.part === part);
}

/** ტესტის ნაკრები — თანაბრად თავების მიხედვით. */
export function buildTest(count: number, seed: number, pool = ALL_QUESTIONS): Question[] {
  return seededShuffle(pool, seed).slice(0, Math.min(count, pool.length));
}

